/**
 * The session cookie, and the token inside it.
 *
 * A session is a row in `customer_session` keyed by the SHA-256 of a random
 * 256-bit token; the cookie carries the token, the database never sees it.
 * Three consequences worth stating, because each one is why this is not a
 * signed JWT:
 *
 *   · logout revokes. Deleting the row ends the session immediately, which a
 *     stateless token cannot do before it expires.
 *   · a database dump is not a set of live sessions.
 *   · "sign out everywhere" is one DELETE, not a key rotation that signs
 *     every other customer out too.
 *
 * The cost is one indexed lookup per authenticated request. Authenticated
 * pages are dynamic regardless — they cannot be prerendered for a specific
 * person — so that read is on a path that was never going to be cached.
 */
import { createHash, randomBytes } from "node:crypto";

import { SESSION_TTL_DAYS } from "@/db/schema";
import { capabilities } from "@/lib/env";

/** Prefixed, because a cookie called `session` tells a reader nothing. */
export const SESSION_COOKIE = "kalt_session";

export const SESSION_TTL_SECONDS = SESSION_TTL_DAYS * 24 * 60 * 60;

export interface MintedSession {
  /** Goes in the cookie, is never written down. */
  readonly token: string;
  /** Goes in the database. */
  readonly tokenHash: Buffer;
}

/**
 * 32 bytes from the CSPRNG, base64url so it survives a cookie header intact.
 *
 * Not a UUID: v4 carries six fixed bits and is routinely generated by
 * libraries that are not cryptographically random. A session token is a
 * bearer credential and should look like one.
 */
export function mintSession(): MintedSession {
  const token = randomBytes(32).toString("base64url");
  return { token, tokenHash: hashSessionToken(token) };
}

export function hashSessionToken(token: string): Buffer {
  return createHash("sha256").update(token).digest();
}

/**
 * `sameSite: "lax"` rather than `strict`.
 *
 * Strict would sign somebody out of the view they arrive at from an email or
 * a search result — the cookie is withheld on the first cross-site
 * navigation, so the page renders signed-out and then flips, which reads as a
 * bug. Lax withholds it on cross-site POST, which is the case that matters.
 *
 * `secure` is off on plain-HTTP localhost only, because a browser silently
 * drops a Secure cookie there and the whole flow appears to do nothing.
 */
export function sessionCookie(token: string, maxAge = SESSION_TTL_SECONDS) {
  return {
    name: SESSION_COOKIE,
    value: token,
    httpOnly: true,
    sameSite: "lax" as const,
    secure: capabilities.isProduction,
    path: "/",
    maxAge,
  };
}

/** The same attributes with an immediate expiry, which is how a cookie is cleared. */
export function clearedSessionCookie() {
  return sessionCookie("", 0);
}
